%% Grain-size analysis
% Grain-size analysis of dry-sieved beach sediments from
% Pea Island National Wildlife Refuge, USA.
%
% Millimetres -> phi -> mass-balance error -> graphical statistics
%
% Author: Gianluca Marino
% Palaeoclimatology Lab, GEOMA,
%Centro de Investigación Mariña, Universidade de Vigo, Spain.

% email addresses: gianluca.marino@uvigo.es, gianluca.marino@uvigo.gal
% Last revision: 03-October-2026
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

clear; close all; clc;

%% 1. Input data
% Sieve openings (mm), ordered from coarse to fine
diameterMM = [8; 4; 2; 1; 0.5; 0.25; 0.125; 0.0625];

% Mass retained on each corresponding sieve (g)
massG = [0; 2.709; 4.771; 23.192; 34.084; ...
         28.129; 6.235; 0.880];

initialMass   = 101.02;% g
recoveredMass = 99.97; % g

%% 2. Convert mm to phi
phi = -log2(diameterMM);

% Sort from lowest to highest phi (coarse to fine)
[phi, idx] = sort(phi);
diameterMM = diameterMM(idx);
massG = massG(idx);

%% 3. Mass-balance error associated with sample loss
% Mass-balance error (%) =
% |initial mass - recovered mass| / initial mass * 100

massBalanceErrorPct = ...
    abs(initialMass - recoveredMass) / initialMass * 100;

massLossG = initialMass - recoveredMass;

fprintf('\n--- Sample mass balance ---\n');
fprintf('Initial mass:       %.3f g\n', initialMass);
fprintf('Recovered mass:     %.3f g\n', recoveredMass);
fprintf('Mass loss:          %.3f g\n', massLossG);
fprintf('Mass-balance error: %.4f%%\n', massBalanceErrorPct);

fractionTotalG = sum(massG);
fractionDifferenceG = fractionTotalG - recoveredMass;

fprintf('Sum of fraction masses: %.3f g\n', fractionTotalG);

if abs(fractionDifferenceG) > 1e-6
    warning(['Listed fraction masses differ from recovered mass ' ...
             'by %+.3f g. Fraction masses are left unchanged.'], ...
             fractionDifferenceG);
end

%% 4. Calculate fraction percentages
% Percentage of the INITIAL sample mass:
massPctInitial = massG / initialMass * 100;

% Percentage of the ANALYSED fraction total:
% normalized to 100% for graphical grain-size statistics.
massPct = massG / fractionTotalG * 100;

% Calculate cumulative retained mass from coarse to fine,
% using the normalized distribution.
% Each value is plotted at the finer boundary of its size class.
cumulativePct = cumsum(massPct);

% The 8 mm sieve (phi = -3) has zero retained mass and provides
% the starting boundary for the histogram and cumulative curve.
assert(massG(1) == 0, ...
    'This histogram layout requires zero mass on the first sieve.');

% Histogram inputs must be row vectors.
binEdges  = phi.';
binCounts = massPct(2:end).';

% Include both percentage calculations in the data table.
inputData = table( ...
    diameterMM, phi, massG, massPctInitial, massPct, cumulativePct, ...
    'VariableNames', { ...
        'SieveMM', ...
        'Phi', ...
        'RetainedG', ...
        'InitialMassPercent', ...
        'AnalysedMassPercent', ...
        'CumulativePercent'});

fprintf('\n--- Grain-size data ---\n');
disp(inputData);

fprintf('Listed fractions as a percentage of initial mass: %.4f%%\n', ...
    sum(massPctInitial));
fprintf('Normalized analysed fractions: %.4f%%\n', sum(massPct));

%% 5. Graphical percentiles
% Read horizontally from a cumulative percentage to the curve,
% then vertically down to the phi axis.
% Linear interpolation estimates these graphical readings.

percentileLevels = [5; 16; 50; 84; 95];
percentilePhi = NaN(size(percentileLevels));

for k = 1:numel(percentileLevels)

    targetPct = percentileLevels(k);
    j = find(cumulativePct >= targetPct, 1, 'first');

    if isempty(j)
        % Do not extrapolate beyond the curve.
        continue

    elseif cumulativePct(j) == targetPct
        percentilePhi(k) = phi(j);

    elseif j > 1
        lowerPct = cumulativePct(j-1);
        upperPct = cumulativePct(j);
        lowerPhi = phi(j-1);
        upperPhi = phi(j);

        percentilePhi(k) = lowerPhi + ...
            (targetPct - lowerPct) / (upperPct - lowerPct) * ...
            (upperPhi - lowerPhi);
    end
end

percentileMM = 2.^(-percentilePhi);

percentileTable = table( ...
    percentileLevels, percentilePhi, percentileMM, ...
    'VariableNames', {'CumulativePercent', 'Phi', 'DiameterMM'});

fprintf('\n--- Graphical percentile readings ---\n');
disp(percentileTable);

%% 6. Graphical mean, median and sorting
phi5  = percentilePhi(1);
phi16 = percentilePhi(2);
phi50 = percentilePhi(3);
phi84 = percentilePhi(4);
phi95 = percentilePhi(5);

% Folk-Ward graphical mean
meanPhi = (phi16 + phi50 + phi84) / 3;

% graphical median
medianPhi = phi50;

% Folk-Ward inclusive graphic standard deviation (sorting)
sortingPhi = (phi84 - phi16) / 4 + ...
             (phi95 - phi5) / 6.6;

% Equivalent grain sizes in mm
meanMM = 2^(-meanPhi);
medianMM = 2^(-medianPhi);

fprintf('\n--- Graphical grain-size statistics ---\n');
fprintf('Graphical mean: %.3f phi (%.4f mm)\n', meanPhi, meanMM);
fprintf('Median:         %.3f phi (%.4f mm)\n', medianPhi, medianMM);
fprintf('Sorting:        %.3f phi\n', sortingPhi);

%% 7. Modal-class midpoint
% All classes have equal width in phi.
% Estimate the mode as the midpoint of the class with greatest mass.
[modalHeight, modalIndex] = max(binCounts);

modalLowerPhi = binEdges(modalIndex);
modalUpperPhi = binEdges(modalIndex+1);

modalPhi = (modalLowerPhi + modalUpperPhi) / 2;
modalMM = 2^(-modalPhi);

fprintf('Modal class:    %.2f to %.2f phi\n', ...
    modalLowerPhi, modalUpperPhi);
fprintf('Modal midpoint: %.2f phi (%.4f mm)\n', modalPhi, modalMM);

%% 8. Create Figure 1
fig = figure(1);
clf(fig);

set(fig, ...
    'Color', 'w', ...
    'Name', 'Grain-size analysis', ...
    'NumberTitle', 'on', ...
    'Position', [100 60 1400 1000]);

% Figure summary: edit its formatting here.
annotation(fig, 'textbox', [0.05 0.95 0.90 0.035], ...
    'String', sprintf( ...
    ['Initial mass: %.2f g    Recovered mass: %.2f g    ' ...
     'Mass-balance error: %.4f%%'], ...
    initialMass, recoveredMass, massBalanceErrorPct), ...
    'EdgeColor', 'none', ...
    'HorizontalAlignment', 'center', ...
    'FontName', 'Arial', ...
    'FontSize', 11, ...
    'FontWeight', 'bold', ...
    'Color', 'k', ...
    'Interpreter', 'none');

%% 9. Histogram
ax1 = axes('Parent', fig, ...
    'Position', [0.08 0.51 0.38 0.37]);

histogram(ax1, ...
    'BinEdges', binEdges, ...
    'BinCounts', binCounts, ...
    'FaceColor', 'm', ...
    'FaceAlpha', 0.25, ...
    'EdgeColor', 'k', ...
    'LineWidth', 1);

hold(ax1, 'on');

% Modal midpoint marker
plot(ax1, modalPhi, modalHeight, 'o', ...
    'MarkerFaceColor', 'w', ...
    'MarkerEdgeColor', 'k', ...
    'MarkerSize', 7, ...
    'LineWidth', 1.2);

% Modal midpoint label: edit its formatting here.
text(ax1, modalPhi, modalHeight + 2, ...
    sprintf('Mode = %.2f \\phi', modalPhi), ...
    'HorizontalAlignment', 'center', ...
    'VerticalAlignment', 'bottom', ...
    'FontName', 'Arial', ...
    'FontSize', 10, ...
    'FontWeight', 'normal', ...
    'Color', 'b', ...
    'Interpreter', 'tex');

% Histogram tick formatting
set(ax1, ...
    'FontName', 'Arial', ...
    'FontSize', 11, ...
    'FontWeight', 'normal', ...
    'XColor', 'k', ...
    'YColor', 'k', ...
    'TickDir', 'in', ...
    'TickLabelInterpreter', 'tex', ...
    'LineWidth', 1, ...
    'Layer', 'bottom', ...
    'Box', 'on', ...
    'XTick', phi.');

xlim(ax1, [phi(1)-0.3 phi(end)+0.3]);
ylim(ax1, [0 1.25*max(massPct)]);

% Histogram title
histTitle = title(ax1, 'Grain-Size Histogram', ...
    'FontName', 'Arial', ...
    'FontSize', 14, ...
    'FontWeight', 'bold', ...
    'Color', 'k', ...
    'Interpreter', 'none');
histTitle.Units = 'normalized';
histTitle.Position = [0.5 1.07 0];

% Histogram horizontal-axis title
xlabel(ax1, 'Grain size (\phi)', ...
    'FontName', 'Arial', ...
    'FontSize', 12, ...
    'FontWeight', 'bold', ...
    'Color', 'k', ...
    'Interpreter', 'tex');

% Histogram vertical-axis title
ylabel(ax1, 'Mass (% of analysed fractions)', ...
    'FontName', 'Arial', ...
    'FontSize', 12, ...
    'FontWeight', 'bold', ...
    'Color', 'k', ...
    'Interpreter', 'none');

%% 10. Cumulative curve
ax2 = axes('Parent', fig, ...
    'Position', [0.58 0.51 0.38 0.37]);

hold(ax2, 'on');

xLeft = phi(1)-0.3;
xRight = phi(end)+0.3;
yBottom = -5;
yTop = 105;

% Solid percentile construction lines
for k = 1:numel(percentileLevels)

    if ~isfinite(percentilePhi(k))
        continue
    end

    p = percentileLevels(k);
    x = percentilePhi(k);

    plot(ax2, [xLeft x], [p p], '-', ...
        'Color', [0.35 0.35 0.35], ...
        'LineWidth', 0.9);

    plot(ax2, [x x], [yBottom p], '-', ...
        'Color', [0.35 0.35 0.35], ...
        'LineWidth', 0.9);
end

% Black cumulative curve
plot(ax2, phi, cumulativePct, '-', ...
    'Color', 'k', ...
    'LineWidth', 1.6);

% Measured points: magenta fill and 40% black edge
plot(ax2, phi, cumulativePct, 'o', ...
    'LineStyle', 'none', ...
    'MarkerSize', 7, ...
    'MarkerFaceColor', 'm', ...
    'MarkerEdgeColor', [0.6 0.6 0.6], ...
    'LineWidth', 1);

% Percentile points: white fill and black edge
valid = isfinite(percentilePhi);

plot(ax2, percentilePhi(valid), percentileLevels(valid), 'o', ...
    'LineStyle', 'none', ...
    'MarkerSize', 7, ...
    'MarkerFaceColor', 'w', ...
    'MarkerEdgeColor', 'k', ...
    'LineWidth', 1.2);

% Cumulative-plot tick formatting
set(ax2, ...
    'FontName', 'Arial', ...
    'FontSize', 11, ...
    'FontWeight', 'normal', ...
    'XColor', 'k', ...
    'YColor', 'k', ...
    'TickDir', 'in', ...
    'TickLabelInterpreter', 'tex', ...
    'LineWidth', 1, ...
    'Layer', 'bottom', ...
    'SortMethod', 'childorder', ...
    'Box', 'on', ...
    'XTick', phi.');

xlim(ax2, [xLeft xRight]);
ylim(ax2, [yBottom yTop]);

% Cumulative-plot title
curveTitle = title(ax2, 'Cumulative Curve', ...
    'FontName', 'Arial', ...
    'FontSize', 14, ...
    'FontWeight', 'bold', ...
    'Color', 'k', ...
    'Interpreter', 'none');
curveTitle.Units = 'normalized';
curveTitle.Position = [0.5 1.07 0];

% Cumulative horizontal-axis title
curveXLabel = xlabel(ax2, 'Grain size (\phi)', ...
    'FontName', 'Arial', ...
    'FontSize', 12, ...
    'FontWeight', 'bold', ...
    'Color', 'k', ...
    'Interpreter', 'tex');
% Keep the horizontal-axis title in its automatic position.

% Cumulative vertical-axis title
ylabel(ax2, 'Cumulative mass (% of analysed fractions)', ...
    'FontName', 'Arial', ...
    'FontSize', 12, ...
    'FontWeight', 'bold', ...
    'Color', 'k', ...
    'Interpreter', 'none');

%% 11. Regular axis ticks and percentile labels

% Regular labelled ticks
set(ax2, ...
    'XTick', phi.', ...
    'XTickLabelMode', 'auto', ...
    'YTick', 0:20:100, ...
    'YTickLabelMode', 'auto', ...
    'TickLabelInterpreter', 'tex');

% Unlabelled ticks between the regular labelled ticks
ax2.XMinorTick = 'on';
ax2.YMinorTick = 'on';

ax2.XAxis.MinorTickValues = ...
    (phi(1:end-1) + phi(2:end)).' / 2;

ax2.YAxis.MinorTickValues = 10:20:90;

% Percentile labels are separate text objects, not axis ticks.
for k = 1:numel(percentileLevels)

    if ~isfinite(percentilePhi(k))
        continue
    end

    x = percentilePhi(k);
    p = percentileLevels(k);

    % Blue percentage label above the horizontal construction line.
    % White background keeps the label readable over the grid.
    text(ax2, xLeft + 0.15, p + 0.8, ...
        sprintf('%g%%', p), ...
        'HorizontalAlignment', 'left', ...
        'VerticalAlignment', 'bottom', ...
        'FontName', 'Arial', ...
        'FontSize', 12, ...
        'FontWeight', 'normal', ...
        'Color', 'b', ...
        'BackgroundColor', 'w', ...
        'EdgeColor', 'none', ...
        'Margin', 1, ...
        'Interpreter', 'none');

    % Blue phi-percentile label inside the plot on its vertical line.
    text(ax2, x, yBottom + 0.5, ...
        sprintf('\\phi_{%d}', percentileLevels(k)), ...
        'HorizontalAlignment', 'center', ...
        'VerticalAlignment', 'bottom', ...
        'FontName', 'Arial', ...
        'FontSize', 12, ...
        'FontWeight', 'normal', ...
        'Color', 'b', ...
        'BackgroundColor', 'w', ...
        'EdgeColor', 'none', ...
        'Margin', 1, ...
        'Interpreter', 'tex', ...
        'Clipping', 'on');
end

ax2.XGrid = 'on';
ax2.YGrid = 'on';
ax2.XMinorGrid = 'on';
ax2.YMinorGrid = 'on';

ax2.GridLineStyle = ':';
ax2.MinorGridLineStyle = ':';

% Black at 20% opacity
ax2.GridColor = [0 0 0];
ax2.MinorGridColor = [0 0 0];
ax2.GridAlpha = 0.20;
ax2.MinorGridAlpha = 0.20;

% Keep the grid behind the curve and markers.
ax2.Layer = 'bottom';
ax2.SortMethod = 'childorder';

%% 12. Input-data table
axTable = axes('Parent', fig, ...
    'Position', [0.06 0.07 0.45 0.29]);

values = inputData{:,:};
[nRows, nCols] = size(values);

axis(axTable, [0 nCols 0 nRows+1]);
axis(axTable, 'off');
hold(axTable, 'on');

% Input-table title
dataTitle = title(axTable, 'Grain-Size Data', ...
    'FontName', 'Arial', ...
    'FontSize', 14, ...
    'FontWeight', 'bold', ...
    'Color', 'k', ...
    'Interpreter', 'none');
dataTitle.Units = 'normalized';
dataTitle.Position = [0.5 1.07 0];

patch(axTable, ...
    [0 nCols nCols 0], ...
    [nRows nRows nRows+1 nRows+1], ...
    [0.92 0.95 0.98], ...
    'EdgeColor', 'none');

headers = {'Sieve (mm)', 'Sieve (\phi)', 'Mass (g)', ...
           'Initial (%)', 'Analysed (%)', 'Cum. (%)'};
formats = {'%.4g', '%.0f', '%.3f', '%.3f', '%.3f', '%.3f'};

for col = 1:nCols

    % Input-table column headings
    text(axTable, col-0.5, nRows+0.5, headers{col}, ...
        'HorizontalAlignment', 'center', ...
        'FontName', 'Arial', ...
        'FontSize', 9, ...
        'FontWeight', 'bold', ...
        'Color', 'k', ...
        'Interpreter', 'tex');

    for row = 1:nRows

        % Input-table numerical values
        text(axTable, col-0.5, nRows+0.5-row, ...
            sprintf(formats{col}, values(row,col)), ...
            'HorizontalAlignment', 'center', ...
            'FontName', 'Arial', ...
            'FontSize', 9, ...
            'FontWeight', 'normal', ...
            'Color', 'k', ...
            'Interpreter', 'none');
    end
end

for y = 0:(nRows+1)
    plot(axTable, [0 nCols], [y y], '-', ...
        'Color', [0.75 0.75 0.75]);
end

for x = 0:nCols
    plot(axTable, [x x], [0 nRows+1], '-', ...
        'Color', [0.75 0.75 0.75]);
end

%% 13. Percentiles and statistics table
axStats = axes('Parent', fig, ...
    'Position', [0.58 0.07 0.38 0.29]);

statNames = {
    '\phi_{5}'
    '\phi_{16}'
    '\phi_{50}'
    '\phi_{84}'
    '\phi_{95}'
    'mean'
    'median'
    'sorting'
};

statPhi = [percentilePhi; meanPhi; medianPhi; sortingPhi];

% Sorting is a spread in phi units, not a grain diameter.
statMM = [percentileMM; meanMM; medianMM; NaN];

nStats = numel(statNames);
columnEdges = [0 1.5 2.5 3.5];
columnCentres = [0.75 2.0 3.0];

axis(axStats, [0 3.5 0 nStats+1]);
axis(axStats, 'off');
hold(axStats, 'on');

% Statistics-table title
statsTitle = title(axStats, 'Grain-Size Statistics', ...
    'FontName', 'Arial', ...
    'FontSize', 14, ...
    'FontWeight', 'bold', ...
    'Color', 'k', ...
    'Interpreter', 'none');
statsTitle.Units = 'normalized';
statsTitle.Position = [0.5 1.07 0];

patch(axStats, ...
    [0 3.5 3.5 0], ...
    [nStats nStats nStats+1 nStats+1], ...
    [0.92 0.95 0.98], ...
    'EdgeColor', 'none');

statHeaders = {'Parameter', 'Value (\phi)', 'Size (mm)'};

for col = 1:3

    % Statistics-table column headings
    text(axStats, columnCentres(col), nStats+0.5, ...
        statHeaders{col}, ...
        'HorizontalAlignment', 'center', ...
        'FontName', 'Arial', ...
        'FontSize', 10, ...
        'FontWeight', 'bold', ...
        'Color', 'k', ...
        'Interpreter', 'tex');
end

for row = 1:nStats

    y = nStats + 0.5 - row;

    % Parameter names
    text(axStats, columnCentres(1), y, statNames{row}, ...
        'HorizontalAlignment', 'center', ...
        'FontName', 'Arial', ...
        'FontSize', 10, ...
        'FontWeight', 'normal', ...
        'Color', 'k', ...
        'Interpreter', 'tex');

    % Values in phi units
    text(axStats, columnCentres(2), y, ...
        sprintf('%.3f', statPhi(row)), ...
        'HorizontalAlignment', 'center', ...
        'FontName', 'Arial', ...
        'FontSize', 10, ...
        'FontWeight', 'normal', ...
        'Color', 'k', ...
        'Interpreter', 'none');

    if isnan(statMM(row))
        mmLabel = '—';
    else
        mmLabel = sprintf('%.4f', statMM(row));
    end

    % Values in millimetres
    text(axStats, columnCentres(3), y, mmLabel, ...
        'HorizontalAlignment', 'center', ...
        'FontName', 'Arial', ...
        'FontSize', 10, ...
        'FontWeight', 'normal', ...
        'Color', 'k', ...
        'Interpreter', 'none');
end

for y = 0:(nStats+1)
    plot(axStats, [0 3.5], [y y], '-', ...
        'Color', [0.75 0.75 0.75]);
end

for x = columnEdges
    plot(axStats, [x x], [0 nStats+1], '-', ...
        'Color', [0.75 0.75 0.75]);
end

